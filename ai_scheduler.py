def get_now_utc() -> datetime:
    return datetime.now(timezone.utc)

def format_iso_utc(dt: datetime) -> str:
    """Safely format timezone-aware datetime to ISO 8601 UTC string with Z suffix."""
    utc_dt = dt.astimezone(timezone.utc)
    return utc_dt.strftime('%Y-%m-%dT%H:%M:%SZ')

def parse_iso_utc(iso_str: str) -> datetime:
    """Safely parse UTC or offset ISO string to timezone-aware UTC datetime."""
    clean = str(iso_str).replace('Z', '+00:00')
    dt = datetime.fromisoformat(clean)
    if dt.tzinfo is None:
        dt = dt.replace(tzinfo=timezone.utc)
    return dt.astimezone(timezone.utc)

