SCHEDULE_TYPES = ('one_time', 'recurring', 'weekly')   # 'recurring' = every day
WEEKDAY_NAMES = ('Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun')   # datetime.weekday() order
TEST_SOURCES = ('ai_generate', 'existing_test')
MAX_LIVE_WINDOW_MINUTES = 1440


def is_recurring(task: Dict[str, Any]) -> bool:
    """Daily and weekly schedules repeat; one-time events complete."""
    return task.get('scheduleType') in ('recurring', 'weekly')


def clean_weekdays(value: Any) -> List[int]:
    """Weekdays as sorted unique ints 0 (Monday) .. 6 (Sunday)."""
    days = set()
    for v in value if isinstance(value, (list, tuple)) else []:
        try:
            d = int(v)
        except (TypeError, ValueError):
            continue
        if 0 <= d <= 6:
            days.add(d)
    return sorted(days)


def _parse_hhmm(value: str) -> Tuple[int, int]:
    hh, mm = [int(x) for x in str(value).strip().split(':')[:2]]
    if not (0 <= hh <= 23 and 0 <= mm <= 59):
        raise ValueError(f"Invalid time '{value}' (use HH:MM, 24-hour IST).")
    return hh, mm


def next_occurrence_ist(from_ist: datetime, time_str: str, weekdays: Optional[List[int]] = None) -> datetime:
    """First moment strictly after from_ist at time_str (IST) on one of weekdays (None = any day)."""
    hh, mm = _parse_hhmm(time_str)
    for add in range(0, 8):
        cand = (from_ist + timedelta(days=add)).replace(hour=hh, minute=mm, second=0, microsecond=0)
        if cand > from_ist and (not weekdays or cand.weekday() in weekdays):
            return cand
    raise ValueError('No matching weekday selected.')


def describe_schedule(task: Dict[str, Any]) -> str:
    if task.get('scheduleType') == 'weekly':
        days = ', '.join(WEEKDAY_NAMES[d] for d in clean_weekdays(task.get('weekdays')))
        return f"Every {days} at {task.get('dailyTime', '09:00')} IST"
    if task.get('scheduleType') == 'recurring':
        return f"Daily at {task.get('dailyTime', '09:00')} IST"
    return f"One-time {task.get('scheduledDate', '')} {task.get('scheduledTime', '')} IST"


def calculate_next_run(task: Dict[str, Any], from_time_utc: Optional[datetime] = None) -> Optional[str]:
    """
    Calculate the next execution timestamp (UTC ISO format) for a scheduled task.
    All scheduled times are strictly interpreted in Indian Standard Time (IST / Asia/Kolkata).
    """
    if not task.get('enabled', True):
        return None
    if task.get('status') in ['cancelled', 'completed', 'deleted']:
        return None

    schedule_type = task.get('scheduleType', 'recurring')
    from_utc = from_time_utc or get_now_utc()
    from_ist = from_utc.astimezone(IST_TZ)

    if schedule_type == 'one_time':
        date_str = str(task.get('scheduledDate', '')).strip()
        time_str = str(task.get('scheduledTime', '09:00')).strip()
        # Fallback to parse scheduledDateTime if date_str is empty
        if not date_str and task.get('scheduledDateTime'):
            dt_raw = str(task.get('scheduledDateTime')).strip()
            if 'T' in dt_raw:
                parts = dt_raw.split('T')
                date_str = parts[0]
                time_str = parts[1][:5]
        if not date_str:
            return None
        try:
            dp = [int(x) for x in date_str.split('-')]
            tp = [int(x) for x in time_str.split(':')]
            dt_ist = datetime(dp[0], dp[1], dp[2], tp[0], tp[1], 0, tzinfo=IST_TZ)
            return format_iso_utc(dt_ist)
        except Exception:
            return None

    else: # recurring daily / weekly on chosen days
        daily_time = str(task.get('dailyTime', '09:00')).strip()
        weekdays = clean_weekdays(task.get('weekdays')) if schedule_type == 'weekly' else None
        if schedule_type == 'weekly' and not weekdays:
            return None
        try:
            return format_iso_utc(next_occurrence_ist(from_ist, daily_time, weekdays))
        except Exception:
            return None

def get_scheduled_tasks(data: Dict[str, Any]) -> List[Dict[str, Any]]:
    """
    Retrieve all non-deleted scheduled tasks from the data store, ensuring list format.
    Filters out tombstones and deleted items.
    """
    raw = data.get('ai_scheduled_tasks')
    if isinstance(raw, dict):
        data['ai_scheduled_tasks'] = list(raw.values())
    elif not isinstance(raw, list):
        data['ai_scheduled_tasks'] = []
    
    # Strictly filter out deleted tasks
    tasks = [
        t for t in data['ai_scheduled_tasks'] 
        if isinstance(t, dict) and t.get('id') and not t.get('isDeleted') and t.get('status') != 'deleted'
    ]
    data['ai_scheduled_tasks'] = tasks

    def _sort_key(t):
        st = t.get('status', 'scheduled')
        # live and processing first, then scheduled, then paused, completed, etc.
        order_map = {'live': 0, 'processing': 1, 'scheduled': 2, 'paused': 3, 'completed': 4, 'expired': 5, 'failed': 6}
        order = order_map.get(st, 7)
        return (order, t.get('nextRunAt') or '9999', t.get('createdAt') or '')
    
    return sorted(tasks, key=_sort_key)

def get_scheduled_task_by_id(task_id: str, data: Dict[str, Any]) -> Optional[Dict[str, Any]]:
    tasks = get_scheduled_tasks(data)
    for t in tasks:
        if t.get('id') == task_id:
            return t
    return None

def save_scheduled_task(task_input: Dict[str, Any], data: Dict[str, Any]) -> Dict[str, Any]:
    """
    Create or update an independent scheduled task.
    Supports both One-Time and Daily Recurring schedules with Live Event windows.
    Strictly validates future IST date/time for One-Time events.
    """
    tasks = get_scheduled_tasks(data)
    task_id = task_input.get('id')
    now_utc = get_now_utc()
    now_iso = format_iso_utc(now_utc)
    now_ist = now_utc.astimezone(IST_TZ)

    schedule_type = task_input.get('scheduleType', 'recurring')
    if schedule_type not in SCHEDULE_TYPES:
        schedule_type = 'recurring'
    weekdays = clean_weekdays(task_input.get('weekdays'))
    if schedule_type == 'weekly' and not weekdays:
        raise ValueError("Select at least one weekday for a weekly schedule.")

    test_source = task_input.get('testSource') or 'ai_generate'
    if test_source not in TEST_SOURCES:
        raise ValueError("Invalid test source.")
    existing_test = None
    if test_source == 'existing_test':
        existing_test_id = str(task_input.get('existingTestId') or '').strip()
        existing_test = next((t for t in data.get('tests', []) if isinstance(t, dict) and t.get('id') == existing_test_id), None)
        if not existing_test:
            raise ValueError("Select an existing MCQ test to host.")

    is_live_event = bool(task_input.get('isLiveEvent', True))
    live_duration_minutes = max(5, min(MAX_LIVE_WINDOW_MINUTES, int(task_input.get('liveDurationMinutes', 15))))

    # Extract & Validate Date / Time in IST
    scheduled_date = str(task_input.get('scheduledDate', '')).strip()
    scheduled_time = str(task_input.get('scheduledTime', '09:00')).strip()
    daily_time = str(task_input.get('dailyTime', '09:00')).strip()

    # Support fallback parsing from scheduledDateTime
    if schedule_type == 'one_time' and not scheduled_date and task_input.get('scheduledDateTime'):
        raw_dt = str(task_input.get('scheduledDateTime')).strip()
        if 'T' in raw_dt:
            parts = raw_dt.split('T')
            scheduled_date = parts[0]
            scheduled_time = parts[1][:5]

    if schedule_type == 'one_time':
        if not scheduled_date or not scheduled_time:
            raise ValueError("Schedule Date (YYYY-MM-DD) and Time (HH:MM) are required for one-time events.")
        try:
            dp = [int(x) for x in scheduled_date.split('-')]
            tp = [int(x) for x in scheduled_time.split(':')]
            dt_ist = datetime(dp[0], dp[1], dp[2], tp[0], tp[1], 0, tzinfo=IST_TZ)
        except Exception as e:
            raise ValueError(f"Invalid scheduled date/time format: {e}")

        # Ensure scheduled time is not in the past (allow 2-min buffer for network drift)
        if dt_ist < (now_ist - timedelta(minutes=2)):
            raise ValueError(f"Scheduled date and time must be in the future (IST). Provided: {scheduled_date} {scheduled_time} IST.")

        starts_at = format_iso_utc(dt_ist)
        dt_expire = dt_ist + timedelta(minutes=live_duration_minutes)
        expires_at = format_iso_utc(dt_expire)
        next_run_at = starts_at

    else: # recurring daily / weekly
        try:
            target_ist = next_occurrence_ist(now_ist, daily_time, weekdays if schedule_type == 'weekly' else None)
        except Exception as e:
            raise ValueError(f"Invalid schedule time: {e}")

        starts_at = format_iso_utc(target_ist)
        expires_at = format_iso_utc(target_ist + timedelta(minutes=live_duration_minutes))
        next_run_at = starts_at

    existing = None
    if task_id:
        for t in tasks:
            if t.get('id') == task_id:
                existing = t
                break

    if not existing:
        task_id = f"sched-{int(time.time() * 1000)}-{uuid.uuid4().hex[:6]}"
        existing = {
            'id': task_id,
            'createdAt': now_iso,
            'executionCount': 0,
            'lastRunAt': None,
            'lastJobId': None,
            'lastTestId': None,
            'lastTestTitle': None,
            'lastError': None,
            'status': 'scheduled'
        }
        if 'ai_scheduled_tasks' not in data or not isinstance(data['ai_scheduled_tasks'], list):
            data['ai_scheduled_tasks'] = []
        data['ai_scheduled_tasks'].append(existing)

    # Update task fields
    existing['name'] = str(task_input.get('name') or task_input.get('title') or 'Scheduled MCQ Practice').strip()
    existing['scheduleType'] = schedule_type
    existing['weekdays'] = weekdays if schedule_type == 'weekly' else []
    existing['testSource'] = test_source
    existing['existingTestId'] = existing_test.get('id') if existing_test else None
    existing['existingTestTitle'] = existing_test.get('title') if existing_test else None
    existing['dailyTime'] = daily_time
    existing['scheduledDate'] = scheduled_date
    existing['scheduledTime'] = scheduled_time
    existing['timezone'] = 'Asia/Kolkata'

    existing['isLiveEvent'] = is_live_event
    existing['liveDurationMinutes'] = live_duration_minutes
    existing['startsAt'] = starts_at
    existing['expiresAt'] = expires_at

    existing['titleTemplate'] = str(task_input.get('titleTemplate') or '[Subject] - [Chapter] Practice Test').strip()
    existing['examLevel'] = task_input.get('examLevel', 'CA Foundation')
    existing['examLevelId'] = task_input.get('examLevelId', 'foundation')
    existing['subject'] = task_input.get('subject', 'Accounting')
    existing['subjectId'] = task_input.get('subjectId', 'sub-1')
    existing['chapter'] = task_input.get('chapter', '')
    existing['chapterId'] = task_input.get('chapterId', '')
    existing['topic'] = str(task_input.get('topic') or existing['chapter'] or 'Daily Practice').strip()
    existing['difficulty'] = task_input.get('difficulty', 'ICAI Exam Standard')
    existing['questionCategory'] = str(task_input.get('questionCategory', existing.get('questionCategory', 'Direct Questions'))).strip()
    existing['questionSpeed'] = str(task_input.get('questionSpeed', existing.get('questionSpeed', 'Quick'))).strip()
    existing['questionCount'] = max(1, min(50, int(task_input.get('questionCount', 5))))
    existing['durationMinutes'] = max(5, min(180, int(task_input.get('durationMinutes', 15))))
    existing['marksPerCorrect'] = float(task_input.get('marksPerCorrect', 2.0))
    existing['negativeMarksPerWrong'] = float(task_input.get('negativeMarksPerWrong', 0.5))
    existing['platformXp'] = float(task_input.get('platformXp', 10.0))
    existing['maxAttempts'] = int(task_input.get('maxAttempts', 3))
    existing['allowedPlans'] = task_input.get('allowedPlans', ['free', 'trial', 'core', 'plus', 'elite'])
    existing['autoPublish'] = bool(task_input.get('autoPublish', True))
    if 'enabled' in task_input:
        existing['enabled'] = bool(task_input.get('enabled'))
    else:
        existing['enabled'] = bool(existing.get('enabled', True))
    existing['updatedAt'] = now_iso

    # Calculate status & next execution time
    if existing.get('enabled'):
        existing['status'] = 'scheduled'
        existing['nextRunAt'] = next_run_at
    else:
        existing['status'] = 'paused'
        existing['nextRunAt'] = None

    return existing

def delete_scheduled_task(
    task_id: str,
    data: Dict[str, Any],
    save_callback: Any = None,
    firebase_sync_callback: Any = None
) -> bool:
    """
    Authoritatively delete a scheduled task from the collection and mark tombstone.
    Guarantees deletion cannot be restored by stale local caches.
    """
    tasks = get_scheduled_tasks(data)
    initial_len = len(tasks)
    
    # Mark tombstone on task object if found
    for t in tasks:
        if t.get('id') == task_id:
            t['isDeleted'] = True
            t['status'] = 'deleted'
            t['enabled'] = False

    data['ai_scheduled_tasks'] = [t for t in tasks if t.get('id') != task_id]
    
    # Record in tombstone list to reject stale merges
    tombstones = data.setdefault('deleted_scheduled_tasks', [])
    if task_id not in tombstones:
        tombstones.append(task_id)

    deleted = len(data['ai_scheduled_tasks']) < initial_len

    if deleted and save_callback:
        try:
            save_callback(data)
        except Exception:
            pass

    if deleted and firebase_sync_callback:
        try:
            firebase_sync_callback(f"ai_scheduled_tasks/{task_id}", None, method='DELETE', sync=True)
        except Exception:
            pass

    return deleted

def toggle_scheduled_task(task_id: str, enabled: bool, data: Dict[str, Any]) -> Optional[Dict[str, Any]]:
    """Enable or pause a scheduled task."""
    task = get_scheduled_task_by_id(task_id, data)
    if not task:
        return None
    task['enabled'] = bool(enabled)
    now_utc = get_now_utc()
    task['updatedAt'] = format_iso_utc(now_utc)
    if task['enabled']:
        if task.get('status') != 'completed':
            task['status'] = 'scheduled'
            task['nextRunAt'] = calculate_next_run(task, now_utc)
    else:
        task['status'] = 'paused'
        task['nextRunAt'] = None
    return task

def cancel_scheduled_task(task_id: str, data: Dict[str, Any]) -> Optional[Dict[str, Any]]:
    """Cancel a scheduled task."""
    task = get_scheduled_task_by_id(task_id, data)
    if not task:
        return None
    task['enabled'] = False
    task['status'] = 'cancelled'
    task['nextRunAt'] = None
    task['updatedAt'] = format_iso_utc(get_now_utc())
    return task

