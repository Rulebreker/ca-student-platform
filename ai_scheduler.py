def dispatch_scheduled_task(
    task: Dict[str, Any],
    data: Dict[str, Any],
    save_callback: Any,
    firebase_sync_callback: Any
) -> Tuple[bool, Optional[str], Optional[Dict[str, Any]]]:
    """
    Start a scheduled task by queuing a generation job for the Local Qwen Worker - the same
    path Generate & Host Now uses. The task stays 'processing' until the job finishes;
    apply_job_outcome_to_task() then hosts the live window / advances the schedule.
    """
    task_id = task.get('id')
    now_iso = format_iso_utc(get_now_utc())
    if task.get('testSource') == 'existing_test':
        return host_existing_test(task, data, save_callback, firebase_sync_callback)
    print(f"[SCHEDULER_DISPATCH] Queuing job for scheduled task '{task.get('name')}' (ID: {task_id})...", flush=True)

    worker_status = ai_job_manager.get_worker_status(data)
    if not worker_status.get('isOnline'):
        err_msg = ("Local Qwen Worker is offline. Start `python local_qwen_worker.py` on the administrator machine; "
                   "the task will run at its next scheduled time.")
        print(f"[SCHEDULER_FAILED_WORKER_OFFLINE] Task '{task.get('name')}': {err_msg}", flush=True)
        _fail_task(task, err_msg, data, save_callback, firebase_sync_callback)
        return False, err_msg, None

    ok, err, job_record = ai_job_manager.create_generation_job(
        build_task_job_params(task), data, save_callback, firebase_sync_callback, scheduled_task_id=task_id)
    if not ok or not job_record:
        err_msg = f"Failed to queue generation job: {err}"
        _fail_task(task, err_msg, data, save_callback, firebase_sync_callback)
        return False, err_msg, None

    task['status'] = 'processing'
    task['activeJobId'] = job_record['id']
    task['claimedAt'] = task.get('claimedAt') or now_iso
    task['updatedAt'] = now_iso
    _persist_task(task, data, save_callback, firebase_sync_callback)
    return True, None, {'job': job_record, 'queuedForWorker': True}


def host_existing_test(
    task: Dict[str, Any],
    data: Dict[str, Any],
    save_callback: Any,
    firebase_sync_callback: Any
) -> Tuple[bool, Optional[str], Optional[Dict[str, Any]]]:
    """Make an already-created MCQ test live for this occurrence (no generation, no worker needed)."""
    test_id = task.get('existingTestId')
    test = next((t for t in data.get('tests', []) if isinstance(t, dict) and t.get('id') == test_id), None)
    if not test:
        err_msg = "The selected test no longer exists. Edit the schedule and choose another test."
        _fail_task(task, err_msg, data, save_callback, firebase_sync_callback)
        return False, err_msg, None
    q_count = sum(1 for q in data.get('questions', []) if isinstance(q, dict) and q.get('testId') == test_id)
    if q_count == 0 and not int(test.get('totalQuestions') or 0):
        err_msg = f"Test '{test.get('title')}' has no questions; it was not made live."
        _fail_task(task, err_msg, data, save_callback, firebase_sync_callback)
        return False, err_msg, None

    now_utc = get_now_utc()
    now_iso = format_iso_utc(now_utc)
    test['isPublished'] = True
    test['updatedAt'] = now_iso
    task['lastRunAt'] = now_iso
    task['lastTestId'] = test_id
    task['lastTestTitle'] = test.get('title')
    task['lastError'] = None
    task['activeJobId'] = None
    task['executionCount'] = task.get('executionCount', 0) + 1
    task['updatedAt'] = now_iso
    if bool(task.get('isLiveEvent', True)):
        expires_at = format_iso_utc(now_utc + timedelta(minutes=int(task.get('liveDurationMinutes', 15))))
        test['isLive'] = True
        test['status'] = 'Live'
        test['liveStartsAt'] = now_iso
        test['liveExpiresAt'] = expires_at
        test.pop('expiredAt', None)
        task['status'] = 'live'
        task['startsAt'] = now_iso
        task['expiresAt'] = expires_at
        task['nextRunAt'] = expires_at  # the tick at expiry ends the live window and advances the schedule
    else:
        test['status'] = 'Published'
        task['status'] = 'scheduled' if is_recurring(task) else 'completed'
        task['nextRunAt'] = calculate_next_run(task, now_utc) if is_recurring(task) else None
    if firebase_sync_callback:
        firebase_sync_callback(f"tests/{test_id}", test, method='PUT', sync=True)
    _persist_task(task, data, save_callback, firebase_sync_callback)
    print(f"[SCHEDULER_HOST_EXISTING] Task '{task.get('name')}' hosted test '{test.get('title')}' ({test_id}) -> {task['status']}.", flush=True)
    return True, None, {'test': {'id': test_id, 'title': test.get('title')}, 'hostedExistingTest': True}


def apply_job_outcome_to_task(
    job: Dict[str, Any],
    test_record: Optional[Dict[str, Any]],
    data: Dict[str, Any],
    firebase_sync_callback: Any = None
) -> None:
    """Called by ai_job_manager when a job linked to a scheduled task finishes (any terminal status)."""
    task = get_scheduled_task_by_id(job.get('scheduledTaskId'), data)
    if not task:
        return
    completed_utc = get_now_utc()
    completed_iso = format_iso_utc(completed_utc)
    task['activeJobId'] = None
    task['lastJobId'] = job.get('id')
    task['updatedAt'] = completed_iso

    if not test_record:
        record_task_failure(task, job.get('error') or f"Generation job {job.get('status')}", completed_utc)
    else:
        test_id = test_record.get('id')
        task['lastRunAt'] = completed_iso
        task['lastTestId'] = test_id
        task['lastTestTitle'] = test_record.get('title')
        task['lastError'] = None if job.get('status') == 'COMPLETED' else job.get('error')
        task['executionCount'] = task.get('executionCount', 0) + 1

        if bool(task.get('isLiveEvent', True)):
            live_dur = int(task.get('liveDurationMinutes', 15))
            starts_at = task.get('startsAt') or completed_iso
            expires_at = task.get('expiresAt')
            if not expires_at or expires_at <= completed_iso:
                expires_at = format_iso_utc(completed_utc + timedelta(minutes=live_dur))
            test_record['isLive'] = True
            test_record['status'] = 'Live'
            test_record['liveStartsAt'] = starts_at
            test_record['liveExpiresAt'] = expires_at
            if firebase_sync_callback:
                firebase_sync_callback(f"tests/{test_id}", test_record, method='PUT', sync=True)
            task['status'] = 'live'
            task['startsAt'] = starts_at
            task['expiresAt'] = expires_at
            task['nextRunAt'] = expires_at  # next tick at expiry time expires the live event
        elif is_recurring(task):
            task['status'] = 'scheduled'
            task['nextRunAt'] = calculate_next_run(task, completed_utc)
        else:
            task['status'] = 'completed'
            task['nextRunAt'] = None

    if firebase_sync_callback:
        firebase_sync_callback(f"ai_scheduled_tasks/{task.get('id')}", task, method='PUT', sync=True)
    print(f"[SCHEDULER_JOB_OUTCOME] Task '{task.get('name')}' -> {task['status']} (job {job.get('id')} {job.get('status')}).", flush=True)

def process_due_tasks(
    data: Dict[str, Any],
    save_callback: Any,
    firebase_sync_callback: Any,
    claim_fn: Any = None
) -> Dict[str, Any]:
    """
    Authoritative state evaluator and executor:
    1. Evaluates all tasks due to go LIVE (status == 'scheduled' and nextRunAt <= now).
    2. Evaluates all active tasks due to EXPIRE (status == 'live' and expiresAt <= now).
    3. Evaluates all tests directly for automatic expiry reconciliation.
    4. Safe for Vercel Cron, opportunistic request triggers, and persistent worker threads.
    """
    now_utc = get_now_utc()
    now_iso = format_iso_utc(now_utc)
    tasks = get_scheduled_tasks(data)

    executed_results = []

    # Phase 0: daily/weekly tasks left 'failed' by older code resume at their next occurrence
    for t in tasks:
        if is_stalled_recurring(t):
            t['status'] = 'scheduled'
            next_run = t.get('nextRunAt')
            if not next_run or next_run <= now_iso:
                t['nextRunAt'] = calculate_next_run(t, now_utc)
            t['updatedAt'] = now_iso
            _persist_task(t, data, save_callback, firebase_sync_callback)
            executed_results.append({'taskId': t.get('id'), 'taskName': t.get('name'), 'action': 'recovered_schedule',
                                     'success': True, 'nextRunAt': t.get('nextRunAt')})

    # Phase 1: Due Start Events (scheduled -> live / completed); one instance per occurrence
    due_to_start = [t for t in tasks if is_due_to_start(t, now_utc)]

    for t in due_to_start:
        claimed, claim_id = attempt_claim_task(t, data, save_callback=save_callback,
                                               firebase_sync_callback=firebase_sync_callback, claim_fn=claim_fn)
        if not claimed:
            continue
        ok, err, res = dispatch_scheduled_task(t, data, save_callback, firebase_sync_callback)
        executed_results.append({
            'taskId': t.get('id'),
            'taskName': t.get('name'),
            'action': ('hosted_existing_test' if (res or {}).get('hostedExistingTest') else 'queued_generation') if ok else 'dispatch_failed',
            'jobId': (res or {}).get('job', {}).get('id'),
            'success': ok,
            'error': err,
            'testId': t.get('lastTestId'),
            'executionId': claim_id
        })

    # Phase 2: Due Expiry Events (live -> expired)
    due_to_expire = []
    for t in tasks:
        if t.get('status') == 'live':
            exp = t.get('expiresAt') or t.get('nextRunAt')
            if exp and exp <= now_iso:
                due_to_expire.append(t)

    for t in due_to_expire:
        # Expire the test
        test_id = t.get('lastTestId')
        if test_id:
            for t_item in data.get('tests', []):
                if t_item.get('id') == test_id:
                    t_item['isLive'] = False
                    t_item['status'] = 'Expired'
                    t_item['expiredAt'] = now_iso
                    if firebase_sync_callback:
                        firebase_sync_callback(f"tests/{test_id}", t_item, method='PUT', sync=True)
                    print(f"[SCHEDULER_EXPIRE] Test '{test_id}' marked EXPIRED.", flush=True)
                    break

        if is_recurring(t):
            t['status'] = 'scheduled'
            # Advance to the next daily / weekly occurrence in IST
            next_start = calculate_next_run(t, now_utc)
            t['startsAt'] = next_start
            t['nextRunAt'] = next_start
            if next_start:
                next_start_dt = parse_iso_utc(next_start)
                t['expiresAt'] = format_iso_utc(next_start_dt + timedelta(minutes=int(t.get('liveDurationMinutes', 15))))
        else: # one-time
            t['status'] = 'completed'
            t['nextRunAt'] = None

        t['updatedAt'] = now_iso
        if save_callback:
            save_callback(data)
        if firebase_sync_callback:
            firebase_sync_callback(f"ai_scheduled_tasks/{t['id']}", t, method='PUT', sync=True)

        executed_results.append({
            'taskId': t.get('id'),
            'taskName': t.get('name'),
            'action': 'expired',
            'success': True,
            'testId': test_id
        })

    # Phase 3: Direct Test Expiry Reconciliation
    for test in data.get('tests', []):
        live_exp = test.get('liveExpiresAt')
        if live_exp and (test.get('isLive') or test.get('status') == 'Live'):
            if now_iso >= live_exp:
                test['isLive'] = False
                test['status'] = 'Expired'
                test['expiredAt'] = now_iso
                if save_callback:
                    save_callback(data)
                if firebase_sync_callback:
                    firebase_sync_callback(f"tests/{test['id']}", test, method='PUT', sync=True)

    # Legacy autopilot backward compatibility
    legacy_cfg = data.get('ai_autopilot_config')
    if not tasks and legacy_cfg and isinstance(legacy_cfg, dict) and legacy_cfg.get('enabled'):
        offset_hours = float(legacy_cfg.get('timezoneOffsetHours', 5.5))
        target_tz = timezone(timedelta(hours=offset_hours))
        now_local = datetime.now(target_tz)
        today_str = now_local.strftime('%Y-%m-%d')
        current_hhmm = now_local.strftime('%H:%M')
        daily_time = legacy_cfg.get('dailyTime', '20:00')

        if legacy_cfg.get('lastRunDate') != today_str and current_hhmm >= daily_time:
            print(f"[AI_SCHEDULER_LEGACY] Triggering legacy autopilot for {today_str} at {current_hhmm}...", flush=True)
            subject_name = legacy_cfg.get('subject', 'Accounting')
            chapter_name = legacy_cfg.get('chapter', 'Daily Practice')
            title_template = legacy_cfg.get('titleTemplate') or 'Auto-Pilot: {subject} - {chapter} Daily Practice'
            job_title = title_template.replace('{subject}', subject_name).replace('{chapter}', chapter_name).replace('{date}', today_str)

            params = {
                'title': job_title,
                'subject': subject_name,
                'subjectId': legacy_cfg.get('subjectId', 'sub-1'),
                'chapter': chapter_name,
                'chapterId': legacy_cfg.get('chapterId', ''),
                'topic': legacy_cfg.get('topic') or chapter_name,
                'examLevel': legacy_cfg.get('examLevel', 'CA Foundation'),
                'examLevelId': legacy_cfg.get('examLevelId', 'foundation'),
                'difficulty': legacy_cfg.get('difficulty', 'ICAI Exam Standard'),
                'count': int(legacy_cfg.get('questionCount', 5)),
                'durationMinutes': int(legacy_cfg.get('durationMinutes', 15)),
                'marksPerCorrect': float(legacy_cfg.get('marksPerCorrect', 2.0)),
                'negativeMarksPerWrong': float(legacy_cfg.get('negativeMarksPerWrong', 0.5)),
                'platformXp': float(legacy_cfg.get('platformXp', 10.0)),
                'maxAttempts': int(legacy_cfg.get('maxAttempts', 3)),
                'allowedPlans': legacy_cfg.get('allowedPlans', ['free', 'trial', 'core', 'plus', 'elite']),
                'autoPublish': bool(legacy_cfg.get('autoPublish', True)),
                'description': legacy_cfg.get('description', ''),
                'instructions': legacy_cfg.get('instructions', '')
            }

            if not ai_job_manager.get_worker_status(data).get('isOnline'):
                ok, err, job_record = False, 'Local Qwen Worker is offline', None
            else:
                ok, err, job_record = ai_job_manager.create_generation_job(params, data, save_callback, firebase_sync_callback)
            if ok and job_record:
                legacy_cfg['lastRunDate'] = today_str
                legacy_cfg['lastRunJobId'] = job_record.get('id')
                if save_callback:
                    save_callback(data)
                if firebase_sync_callback:
                    firebase_sync_callback('ai_autopilot_config', legacy_cfg, method='PUT', sync=True)
                executed_results.append({
                    'taskId': 'legacy_autopilot',
                    'taskName': 'Legacy Auto-Pilot',
                    'success': True,
                    'error': None,
                    'jobId': job_record.get('id')
                })

    return {
        'success': True,
        'executedCount': len(executed_results),
        'results': executed_results,
        'serverTimeUtc': now_iso,
        'serverTimeIst': now_utc.astimezone(IST_TZ).strftime('%Y-%m-%d %H:%M:%S IST')
    }

